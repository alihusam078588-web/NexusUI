from pathlib import Path, PurePosixPath
import re

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
OUT = ROOT / "dist" / "Nexus.lua"

# Correct two references for the documented ModuleScript folder layout.
fixes = {
    "Nexus.lua": {
        "require(script.Core.Window)": "require(script.Parent.Core.Window)",
        "require(script.Themes.ThemeManager)": "require(script.Parent.Themes.ThemeManager)",
    },
    "Themes/ThemeManager.lua": {
        "require(script.NEXUSDark)": "require(script.Parent.NEXUSDark)",
        "require(script.Adaptive)": "require(script.Parent.Adaptive)",
    },
}
for relative, replacements in fixes.items():
    path = SRC / relative
    source = path.read_text(encoding="utf-8")
    for old, new in replacements.items():
        source = source.replace(old, new)
    path.write_text(source, encoding="utf-8")

files = sorted(SRC.rglob("*.lua"))
modules = {p.relative_to(SRC).with_suffix("").as_posix(): p for p in files}

# These references are a folder alias used by Core/Section.lua; they become
# explicit module IDs in the bundled output.
components_alias = re.compile(
    r"(?m)^\s*local\s+Components\s*=\s*script\.Parent\.Parent\.Components\s*\n?"
)
script_require = re.compile(r"require\s*\(\s*(script(?:\.[A-Za-z_][A-Za-z0-9_]*)+)\s*\)")
component_require = re.compile(r"require\s*\(\s*Components\.([A-Za-z_][A-Za-z0-9_]*)\s*\)")


def resolve_script_path(module_id: str, expression: str) -> str:
    # The script object is the ModuleScript itself, so start at its full path.
    parts = module_id.split("/")
    for segment in expression.split(".")[1:]:
        if segment == "Parent":
            if not parts:
                raise ValueError(f"Invalid Parent traversal in {module_id}: {expression}")
            parts.pop()
        else:
            parts.append(segment)
    return "/".join(parts)

factories = []
errors = []
for module_id, path in modules.items():
    source = path.read_text(encoding="utf-8")
    source = components_alias.sub("", source)

    def replace_script(match):
        target = resolve_script_path(module_id, match.group(1))
        if target not in modules:
            errors.append(f"{module_id}: unresolved {match.group(1)} -> {target}")
        return f'__require("{target}")'

    source = script_require.sub(replace_script, source)

    def replace_component(match):
        target = f"Components/{match.group(1)}"
        if target not in modules:
            errors.append(f"{module_id}: unresolved Components.{match.group(1)}")
        return f'__require("{target}")'

    source = component_require.sub(replace_component, source)

    # There should be no Roblox instance-tree module references left.
    code_without_comments = re.sub(r"(?m)^\s*--.*$", "", source)
    if re.search(r"\bscript\b|(?<![A-Za-z_])require\s*\(", code_without_comments):
        errors.append(f"{module_id}: unsupported script/require reference remains")

    factories.append(
        f'__factories["{module_id}"] = function()\n{source.rstrip()}\nend\n'
    )

if errors:
    raise SystemExit("Bundle failed:\n- " + "\n- ".join(errors))

header = '''-- NEXUS UI 1.0.0 | Generated single-file bundle.
-- Build source: src/ | Generated by build.py
-- Use in an environment that supports loadstring and game:HttpGet.

local __factories = {}
local __cache = {}
local __loading = {}

local function __require(name)
    if __cache[name] ~= nil then
        return __cache[name]
    end
    if __loading[name] then
        error("NEXUS UI: circular module dependency: " .. name, 2)
    end
    local factory = __factories[name]
    if not factory then
        error("NEXUS UI: module not found: " .. name, 2)
    end
    __loading[name] = true
    local ok, result = pcall(factory)
    __loading[name] = nil
    if not ok then
        error(result, 2)
    end
    if result == nil then
        result = true
    end
    __cache[name] = result
    return result
end

'''

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(header + "\n".join(factories) + '\nreturn __require("Nexus")\n', encoding="utf-8")
print(f"Built {OUT.relative_to(ROOT)}")
print(f"Bundled {len(modules)} Luau modules; {OUT.stat().st_size:,} bytes")
